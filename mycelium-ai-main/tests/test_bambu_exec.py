class _FakeSocket:
    """Scripted FTPS peer: banner, canned replies, byte sink."""

    def __init__(self, script, size_fn=None):
        self._script = list(script)
        self._size_fn = size_fn
        self.sent = []
        self.inbox = b""
        self.timeout = None
        self.closed = False

    def makefile(self, mode):
        parent = self

        class _Reader:
            def readline(self):
                if parent._script:
                    return (parent._script.pop(0) + "\r\n").encode()
                if parent._size_fn is not None and parent.sent \
                        and parent.sent[-1].startswith(b"SIZE"):
                    return (f"213 {parent._size_fn()}\r\n").encode()
                return b""

            def close(self):
                pass

        return _Reader()

    def sendall(self, data):
        self.sent.append(data)
        if data.startswith(b"STOR"):
            self.inbox = b""

    def settimeout(self, value):
        self.timeout = value

    def close(self):
        self.closed = True

    def shutdown(self, _how):
        pass


class _FakeDial:
    def __init__(self, control, data_bytes=b""):
        self.control = control
        self.data_sockets = []
        self._data_bytes = data_bytes
        self.wrapped = []

    def connect(self, host, port, timeout):
        sock = _FakeSocket([]) if port != 990 else self.control
        if port != 990:
            self.data_sockets.append(sock)
        return sock

    def wrap_tls(self, sock):
        self.wrapped.append(sock)
        return sock


