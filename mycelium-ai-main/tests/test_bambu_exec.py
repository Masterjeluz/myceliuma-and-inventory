class _FakeMqtt:
    """Recording MQTT client: publish allowed, everything logged."""

    def __init__(self):
        self.published = []

    def publish(self, topic, payload, qos=1):
        self.published.append((topic, payload, qos))
        info = types.SimpleNamespace(rc=0, mid=1)
        return info


class _StopAwareMqtt(_FakeMqtt):
    """Flips the linked fake adapter to IDLE on stop."""

    def __init__(self, adapter):
        super().__init__()
        self._adapter = adapter

    def publish(self, topic, payload, qos=1):
        info = super().publish(topic, payload, qos)
        try:
            body = json.loads(payload)
            if body.get("print", {}).get("command") == "stop":
                self._adapter._live["gcode_state"] = "IDLE"
        except (ValueError, AttributeError):
            pass
        return info


