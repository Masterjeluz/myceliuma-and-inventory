def test_ftps_dialect_order_and_pasv_discard():
    from coordinator.app.bambu_exec import _Dial, _Ftps
    control = _FakeSocket(_control_script())
    dial = _FakeDial(control)
    session = dial.wrap_tls(control)
    ftp = _Ftps(session, "192.168.1.50", dial)
    ftp.login("bblp", "secret-woord")
    ftp.prepare()
    ftp.upload("kubus.gcode.3mf", b"123456789012",
               transfer_timeout=60.0)
    assert ftp.size("kubus.gcode.3mf") == 12
    verbs = [line for line in control.sent]
    assert verbs[0].split(b" ")[0] == b"USER"
    assert verbs[0].split(b" ")[1].strip() == b"bblp"
    order = [v.split(b" ")[0] for v in control.sent]
    assert order.index(b"TYPE") < order.index(b"PBSZ") < \
        order.index(b"PROT")
    stor_index = order.index(b"STOR")
    assert order.index(b"PASV") < stor_index
    assert dial.data_sockets, "data socket must be separate"
    flat = b" ".join(control.sent)
    verbs_only = b" ".join(
        line.split(b" ")[0] for line in control.sent)
    assert b"secret-woord" not in verbs_only
    assert b"PASS" in verbs_only, "PASS-verb moet op de draad"
    assert ftp.verbs[:6] == ["USER", "PASS", "TYPE", "PBSZ",
                             "PROT", "DELE"], ftp.verbs
    ftp.quit()


