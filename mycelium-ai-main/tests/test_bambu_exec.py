def test_plate_3mf_roundtrip():
    from coordinator.app.local_slicer import PLACEHOLDER_PNG
    blob = build_plate_3mf(
        GCODE, profile_name="fine-pla", material="PLA",
        color_hex="#FFFFFF", weight_g=4.12, prediction_s=600,
        support_used=False, base_settings={"bed_type": "x"})
    assert blob[:2] == b"PK"
    archive = zipfile.ZipFile(io.BytesIO(blob))
    assert archive.read("Metadata/plate_1.gcode") == GCODE
    import hashlib
    assert archive.read("Metadata/plate_1.gcode.md5").decode() == \
        hashlib.md5(GCODE).hexdigest().upper()
    model_settings = archive.read(
        "Metadata/model_settings.config").decode()
    assert model_settings.index("filament_volume_maps") < \
        model_settings.index("gcode_file")
    slice_info = archive.read("Metadata/slice_info.config").decode()
    assert slice_info.index("extruder_type") < \
        slice_info.index("printer_model_id")
    assert "4.12" in slice_info
    assert archive.read("Metadata/plate_1.png") == PLACEHOLDER_PNG
    project = json.loads(
        archive.read("Metadata/project_settings.config"))
    assert project["profile"] == "fine-pla"
    try:
        build_plate_3mf(b"", profile_name="x", material="PLA")
        raise AssertionError("empty gcode accepted")
    except ValueError:
        pass


