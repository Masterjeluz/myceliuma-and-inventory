class _NoRedirect(urllib.request.HTTPRedirectHandler):
    """Refuse redirects: the loopback bridge never follows them."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):  # type: ignore[override]
        raise urllib.error.HTTPError(
            newurl, code, "redirects are never followed; refusing",
            headers, fp,
        )


def _opener(timeout: float) -> urllib.request.OpenerDirector:
    return urllib.request.build_opener(_NoRedirect())


def http_post_json(
    url: str, payload: dict, timeout: float = 5.0
) -> tuple[int, dict | None, str]:
    """POST JSON, bounded. Returns (status, body-or-None, error)."""
    data = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with _opener(timeout).open(request, timeout=timeout) as response:
            status = int(getattr(response, "status", 200) or 200)
            raw = response.read(65536).decode("utf-8", errors="replace")
    except urllib.error.HTTPError as error:
        return int(error.code or 0), None, f"HTTP {error.code}"
    except Exception as error:
        return 0, None, f"unreachable: {error}"
    try:
        body = json.loads(raw) if raw.strip() else None
    except ValueError:
        body = None
    return status, body, ""


def http_get_json(
    url: str, timeout: float = 5.0
) -> tuple[int, dict | list | None, str]:
    """GET JSON, bounded. Returns (status, body-or-None, error)."""
    request = urllib.request.Request(url, method="GET")
    try:
        with _opener(timeout).open(request, timeout=timeout) as response:
            status = int(getattr(response, "status", 200) or 200)
            raw = response.read(65536).decode("utf-8", errors="replace")
    except urllib.error.HTTPError as error:
        return int(error.code or 0), None, f"HTTP {error.code}"
    except Exception as error:
        return 0, None, f"unreachable: {error}"
    try:
        body = json.loads(raw) if raw.strip() else None
    except ValueError:
        body = None
    return status, body, ""


HttpPost = Callable[[str, dict, float], tuple[int, dict | None, str]]
HttpGet = Callable[[str, float], tuple[int, dict | list | None, str]]


def bootstrap_register(
    *,
    coordinator_url: str,
    node_id: str,
    tier: str = DEFAULT_TIER,
    capabilities: list[str] | None = None,
    token: str = "",
    poll_seconds: float = DEFAULT_POLL_SECONDS,
    post: HttpPost = http_post_json,
    get: HttpGet = http_get_json,
) -> dict:
    """One-time explicit bootstrap: register + heartbeat + verify.

    Uses ONLY the existing coordinator endpoints. The node loop itself
    repeats the same calls on every start; this is just the visible
    first run. Never called implicitly by install().
    """
    url_check = validate_coordinator_url(coordinator_url)
    if not url_check["ok"]:
        return {"ok": False, "error": url_check["error"]}
    id_check = validate_node_id(node_id)
    if not id_check["ok"]:
        return {"ok": False, "error": id_check["error"]}
    if len(str(token or "").strip()) < MIN_TOKEN_CHARS:
        return {
            "ok": False,
            "error": f"node token must be at least {MIN_TOKEN_CHARS} characters",
        }
    try:
        caps = check_capabilities(list(capabilities or ["node.status"]))
    except (ValueError, TypeError) as error:
        return {"ok": False, "error": str(error)}
    base = url_check["url"].rstrip("/") + "/api/v1"
    secret = str(token).strip()
    registration = {
        "node_id": id_check["node_id"],
        "hostname": platform.node() or id_check["node_id"],
        "tier": tier if tier in VALID_TIERS else DEFAULT_TIER,
        "capabilities": caps,
        "cpu_cores": cpu_count(),
        "memory_mb": memory_mb(),
        "energy_source": "unknown",
        "node_token": secret,
    }
    status, _, error = post(f"{base}/nodes/register", registration, 5.0)
    if status not in (200, 201):
        hint = "new identities bind on first register; existing ones need the same token"
        return {
            "ok": False,
            "error": f"registration refused ({error or status}); {hint}",
        }
    beat_status, _, beat_error = post(
        f"{base}/nodes/{id_check['node_id']}/heartbeat",
        {"available": True, "node_token": secret},
        5.0,
    )
    if beat_status not in (200, 204):
        return {
            "ok": False,
            "error": f"registered but heartbeat refused ({beat_error or beat_status})",
        }
    node_status, node_body, _ = get(
        f"{base}/nodes/{id_check['node_id']}", 5.0
    )
    visible = node_status == 200
    return {
        "ok": True,
        "error": "",
        "node_id": id_check["node_id"],
        "coordinator_url": url_check["url"],
        "capabilities": caps,
        "visible_in_api": visible,
        "node": node_body if isinstance(node_body, dict) else {},
        "poll_seconds": poll_seconds,
    }


