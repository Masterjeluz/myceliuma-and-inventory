def _add_common(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--coordinator", default=DEFAULT_COORDINATOR_URL)
    parser.add_argument("--node-id", default=DEFAULT_NODE_ID)
    parser.add_argument("--tier", default=DEFAULT_TIER,
                        choices=list(VALID_TIERS))
    parser.add_argument("--capability", action="append", default=[],
                        help="repeatable; Linux starter set only")
    parser.add_argument("--poll-seconds", type=float,
                        default=DEFAULT_POLL_SECONDS)
    parser.add_argument("--config", default="",
                        help="env file path (default ~/.config/mycelium/node.env)")
    parser.add_argument("--repo-dir", default="",
                        help="checkout dir (default: current directory)")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="mycelium-node",
        description="Mycelium Linux node installer (pull-only, no root needed)",
    )
    sub = parser.add_subparsers(dest="command", required=True)
    install = sub.add_parser("install", help="idempotent local install")
    _add_common(install)
    install.add_argument("--token", default="",
                         help="node token (or MYCELIUM_NODE_TOKEN env)")
    install.add_argument("--with-systemd", action="store_true",
                         help="also install the systemd --user unit")
    install.add_argument("--bootstrap", action="store_true",
                         help="also register + heartbeat once (needs coordinator up)")
    doctor_p = sub.add_parser("doctor", help="local diagnostics")
    doctor_p.add_argument("--config", default="")
    sysd = sub.add_parser("print-systemd", help="print the user unit")
    _add_common(sysd)
    uninstall = sub.add_parser("uninstall", help="safe local removal")
    uninstall.add_argument("--config", default="")
    uninstall.add_argument("--remove-config", action="store_true")
    uninstall.add_argument("--remove-venv", action="store_true")
    uninstall.add_argument("--repo-dir", default="")
    return parser


def _print_rows(rows: list[dict], known: tuple[str, ...] = ()) -> None:
    width = max(len(row["name"]) for row in rows) if rows else 10
    for row in rows:
        print(f"{row['name']:<{width}}  {row['status']:<9}  "
              f"{redact_secrets(row['detail'], known)}")


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    config = parser.parse_args(argv)
    cfg_path = getattr(config, "config", "") or None

    if config.command == "doctor":
        report = doctor(config_path=cfg_path)
        print("Mycelium Node Doctor\n")
        _print_rows(report["rows"])
        print(f"\nconfig: {report['config_path']}")
        return 0 if report["ok"] else 1

    if config.command == "print-systemd":
        try:
            unit = build_systemd_unit(
                repo_dir=config.repo_dir or os.getcwd(),
                coordinator=validate_coordinator_url(
                    config.coordinator)["url"],
                node_id=validate_node_id(config.node_id).get("node_id", "linux-laptop-1"),
                tier=config.tier,
                capabilities=config.capability or None,
                poll_seconds=validate_poll_seconds(
                    config.poll_seconds).get("poll_seconds",
                                             DEFAULT_POLL_SECONDS),
            )
        except (ValueError, TypeError) as error:
            print(f"refused: {error}")
            return 2
        print(unit)
        print("# install as ~/.config/systemd/user/mycelium-node.service, then:")
        print("#   systemctl --user daemon-reload && "
              "systemctl --user enable --now mycelium-node")
        return 0

    if config.command == "uninstall":
        report = uninstall_node(
            config_path=cfg_path,
            remove_config=config.remove_config,
            remove_venv=config.remove_venv,
            repo_dir=config.repo_dir or "",
        )
        for item in report["removed"]:
            print(f"removed: {item}")
        for item in report["kept"]:
            print(f"kept: {item}")
        if not report["ok"]:
            print(f"error: {redact_secrets(report['error'])}")
            return 1
        print("hint: systemctl --user disable --now mycelium-node "
              "(if the service was enabled)")
        return 0

    if config.command == "install":
        repo_dir = config.repo_dir or os.getcwd()
        result = install_node(
            config_path=cfg_path,
            coordinator=config.coordinator,
            node_id=config.node_id,
            tier=config.tier,
            capabilities=config.capability or None,
            poll_seconds=config.poll_seconds,
            token=config.token or None,
        )
        if not result["ok"]:
            print(f"install refused: {result['error']}")
            return 2
        token_value = load_env_file(result["config_path"]).get(
            "MYCELIUM_NODE_TOKEN", "")
        known = (token_value,) if token_value else ()
        print(f"coordinator : {result['coordinator_url']} "
              f"({result['coordinator_scope']})")
        print(f"node        : {result['node_id']} ({result['tier']})")
        print(f"capabilities: {', '.join(result['capabilities'])}")
        print(f"config      : {result['config_path']} "
              f"({'updated' if result['changed'] else 'unchanged'})")
        if result["token_generated"]:
            print("identity    : new token generated (stored chmod 600, "
                  "shown nowhere)")
        elif result["identity_preserved"]:
            print("identity    : existing token preserved")
        else:
            print("identity    : token stored from env/flag")
        for probe in ("ollama", "nvidia"):
            item = result["probes"][probe]
            print(f"{item['name'].lower():<12}: {item['status']} - "
                  f"{redact_secrets(item['detail'], known)}")
        if config.with_systemd:
            unit = build_systemd_unit(
                repo_dir=repo_dir,
                coordinator=result["coordinator_url"],
                node_id=result["node_id"],
                tier=result["tier"],
                capabilities=result["capabilities"],
                poll_seconds=result["poll_seconds"],
            )
            sysd_result = install_systemd_unit(unit)
            print(f"systemd     : {sysd_result['path']} "
                  f"({'written' if sysd_result['changed'] else 'unchanged'})")
            print("systemd     : run 'systemctl --user daemon-reload && "
                  "systemctl --user enable --now mycelium-node'")
        if config.bootstrap:
            stored = load_env_file(result["config_path"])
            boot = bootstrap_register(
                coordinator_url=result["coordinator_url"],
                node_id=result["node_id"],
                tier=result["tier"],
                capabilities=result["capabilities"],
                token=stored.get("MYCELIUM_NODE_TOKEN", ""),
                poll_seconds=result["poll_seconds"],
            )
            if not boot["ok"]:
                print(f"bootstrap   : refused: "
                      f"{redact_secrets(boot['error'], known)}")
                return 1
            print(f"bootstrap   : registered, heartbeat ok, "
                  f"API visible: {boot['visible_in_api']}")
        print("\nstart the node:")
        cap_flags = " ".join(
            f"--capability {cap}" for cap in result["capabilities"]
        )
        print(f"  source {result['config_path']} 2>/dev/null; "
              f"python -m node_client.main --coordinator "
              f"{result['coordinator_url']} --node-id {result['node_id']} "
              f"--tier {result['tier']} {cap_flags} --poll-seconds "
              f"{result['poll_seconds']}")
        print("check health: python -m node_client.install doctor")
        return 0

    parser.print_help()
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
