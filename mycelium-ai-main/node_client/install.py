def default_config_path() -> str:
    """~/.config/mycelium/node.env (overridable via --config)."""
    base = os.environ.get("XDG_CONFIG_HOME", "") or os.path.join(
        os.path.expanduser("~"), ".config"
    )
    return os.path.join(base, "mycelium", "node.env")


def load_env_file(path: str) -> dict[str, str]:
    """Read a KEY=VALUE env file. Missing file -> {}. Never raises."""
    values: dict[str, str] = {}
    try:
        with open(path, encoding="utf-8") as handle:
            content = handle.read()
    except OSError:
        return values
    for line in content.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].strip()
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key and key in CONFIG_KEYS:
            values[key] = value
    return values


def write_env_file(path: str, values: dict[str, str]) -> bool:
    """Write KEY=VALUE env file with mode 600. Returns True if changed."""
    lines = [INSTALLER_MARKER]
    for key in CONFIG_KEYS:
        if key in values and str(values[key] or "") != "":
            value = str(values[key])
            if any(char in value for char in " \t\"'#"):
                value = '"' + value.replace('"', '\\"') + '"'
            lines.append(f"{key}={value}")
    content = "\n".join(lines) + "\n"
    existing = ""
    try:
        with open(path, encoding="utf-8") as handle:
            existing = handle.read()
    except OSError:
        existing = ""
    if existing == content:
        _ensure_mode_600(path)
        return False
    parent = os.path.dirname(path)
    if parent:
        os.makedirs(parent, exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)
    _ensure_mode_600(path)
    return True


def _ensure_mode_600(path: str) -> None:
    try:
        os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)
    except OSError:
        pass


def ensure_token(existing: str | None = None) -> tuple[str, bool]:
    """Keep a strong existing token; generate otherwise.

    Returns (token, generated). Generation matches
    coordinator.app.nodes.generate_token (64 hex chars).
    """
    text = str(existing or "").strip()
    if len(text) >= MIN_TOKEN_CHARS:
        return text, False
    return secrets.token_hex(32), True


# ---------------------------------------------------------------------------
# install orchestration (idempotent)
# ---------------------------------------------------------------------------

def install_node(
    *,
    config_path: str | None = None,
    coordinator: str = DEFAULT_COORDINATOR_URL,
    node_id: str = DEFAULT_NODE_ID,
    tier: str = DEFAULT_TIER,
    capabilities: list[str] | None = None,
    poll_seconds: float = DEFAULT_POLL_SECONDS,
    token: str | None = None,
    runner: Runner = default_runner,
) -> dict:
    """Idempotent local install. Never touches the network.

    - validates coordinator URL / node id / tier / caps / poll interval
    - keeps an existing node id + token (identity is never rotated here)
    - generates a token only when none (or a weak one) exists
    - writes the env file (chmod 600) only when content changed
    - optional Ollama/NVIDIA absence is informational, never fatal
    """
    path = config_path or default_config_path()
    url_check = validate_coordinator_url(coordinator)
    if not url_check["ok"]:
        return {"ok": False, "error": url_check["error"], "changed": False}
    id_check = validate_node_id(node_id)
    if not id_check["ok"]:
        return {"ok": False, "error": id_check["error"], "changed": False}
    if tier not in VALID_TIERS:
        return {
            "ok": False,
            "error": f"tier must be one of {list(VALID_TIERS)}",
            "changed": False,
        }
    poll_check = validate_poll_seconds(poll_seconds)
    if not poll_check["ok"]:
        return {"ok": False, "error": poll_check["error"], "changed": False}
    try:
        if capabilities:
            caps = check_capabilities(list(capabilities))
        else:
            ollama = check_ollama(runner)
            caps = detect_capabilities(
                ollama_available=ollama["status"] == "AVAILABLE"
            )
    except (ValueError, TypeError) as error:
        return {"ok": False, "error": str(error), "changed": False}

    existing = load_env_file(path)
    # Identity preservation: an existing node id / token always wins
    # over installer flags (flags only fill gaps).
    final_id = existing.get("MYCELIUM_NODE_ID", "").strip() or id_check["node_id"]
    id_recheck = validate_node_id(final_id)
    if not id_recheck["ok"]:
        return {"ok": False, "error": id_recheck["error"], "changed": False}
    candidate_token = (
        token.strip()
        if isinstance(token, str) and token.strip()
        else os.environ.get("MYCELIUM_NODE_TOKEN", "").strip()
        or existing.get("MYCELIUM_NODE_TOKEN", "")
    )
    final_token, generated = ensure_token(candidate_token)

    values = {
        "MYCELIUM_COORDINATOR_URL": url_check["url"],
        "MYCELIUM_NODE_ID": final_id,
        "MYCELIUM_NODE_TIER": tier,
        "MYCELIUM_NODE_TOKEN": final_token,
        "MYCELIUM_NODE_CAPABILITIES": ",".join(caps),
        "MYCELIUM_NODE_POLL_SECONDS": str(poll_check["poll_seconds"]),
    }
    # Keep an existing tier/poll choice when flags carry defaults? No:
    # explicit installer flags are the operator's voice, except identity.
    changed = write_env_file(path, values)
    probes = {
        "ollama": check_ollama(runner),
        "nvidia": check_nvidia(runner),
    }
    return {
        "ok": True,
        "changed": changed,
        "config_path": path,
        "coordinator_url": url_check["url"],
        "coordinator_scope": url_check["scope"],
        "node_id": final_id,
        "tier": tier,
        "capabilities": caps,
        "poll_seconds": poll_check["poll_seconds"],
        "token_generated": generated,
        "identity_preserved": bool(existing.get("MYCELIUM_NODE_TOKEN", "")),
        "probes": probes,
        "error": "",
    }


# ---------------------------------------------------------------------------
# systemd user service (least privilege, no root)
# ---------------------------------------------------------------------------

def build_systemd_unit(
    *,
    repo_dir: str,
    coordinator: str,
    node_id: str,
    tier: str = DEFAULT_TIER,
    capabilities: list[str] | None = None,
    poll_seconds: float = DEFAULT_POLL_SECONDS,
    env_file: str | None = None,
) -> str:
    """Render a systemd --user unit. Secrets come from EnvironmentFile."""
    caps = check_capabilities(list(capabilities or ["node.status"]))
    cap_flags = " ".join(f"--capability {cap}" for cap in caps)
    env = env_file or os.path.join(
        os.path.expanduser("~"), ".config", "mycelium", "node.env"
    )
    return f"""{INSTALLER_MARKER}
[Unit]
Description=Mycelium node {node_id} (pull-only, user service)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory={repo_dir}
EnvironmentFile={env}
ExecStart={repo_dir}/.venv/bin/python -m node_client.main --coordinator {coordinator} --node-id {node_id} --tier {tier} {cap_flags} --poll-seconds {poll_seconds}
Restart=on-failure
RestartSec=15
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=default.target
"""


def default_systemd_path() -> str:
    """~/.config/systemd/user/mycelium-node.service."""
    base = os.environ.get("XDG_CONFIG_HOME", "") or os.path.join(
        os.path.expanduser("~"), ".config"
    )
    return os.path.join(base, "systemd", "user", SERVICE_NAME)


def install_systemd_unit(
    unit_text: str, path: str | None = None
) -> dict:
    """Write the user unit file. Returns {ok, changed, path}."""
    target = path or default_systemd_path()
    parent = os.path.dirname(target)
    if parent:
        os.makedirs(parent, exist_ok=True)
    try:
        with open(target, encoding="utf-8") as handle:
            existing = handle.read()
    except OSError:
        existing = ""
    if existing == unit_text:
        return {"ok": True, "changed": False, "path": target}
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(unit_text)
    return {"ok": True, "changed": True, "path": target}


