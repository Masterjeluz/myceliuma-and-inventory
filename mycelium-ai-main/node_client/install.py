def doctor(
    *,
    config_path: str | None = None,
    runner: Runner = default_runner,
    get: HttpGet = http_get_json,
) -> dict:
    """Local diagnostics for old laptops. Returns rows + overall ok."""
    path = config_path or default_config_path()
    rows: list[dict] = []
    detected = detect_os()
    rows.append({
        "name": "OS",
        "status": "OK" if detected["is_linux"] else "FAIL",
        "detail": (
            f"{detected['distro'] or detected['system']} "
            f"({detected['machine']})".strip()
        ),
    })
    rows.append(check_python_version())
    rows.append(check_git(runner))

    config = load_env_file(path)
    rows.append({
        "name": "Config",
        "status": "OK" if config else "FAIL",
        "detail": path if config else f"missing: {path} (run install first)",
    })
    stored_token = str(config.get("MYCELIUM_NODE_TOKEN", "") or "")
    env_token = str(os.environ.get("MYCELIUM_NODE_TOKEN", "") or "").strip()
    effective = stored_token.strip() or env_token
    if len(effective) >= MIN_TOKEN_CHARS:
        rows.append({
            "name": "Identity",
            "status": "OK",
            "detail": f"token present ({len(effective)} chars, value hidden)",
        })
    elif effective:
        rows.append({
            "name": "Identity",
            "status": "FAIL",
            "detail": f"token too short (needs >= {MIN_TOKEN_CHARS} chars)",
        })
    else:
        rows.append({
            "name": "Identity",
            "status": "FAIL",
            "detail": "no token (run install first)",
        })

    coordinator = str(config.get("MYCELIUM_COORDINATOR_URL", "") or "").strip()
    node_id = str(config.get("MYCELIUM_NODE_ID", "") or "").strip()
    url_check = validate_coordinator_url(coordinator) if coordinator else {"ok": False}
    if not coordinator or not url_check.get("ok"):
        rows.append({
            "name": "Coordinator",
            "status": "FAIL",
            "detail": "no valid coordinator URL in config",
        })
        rows.append({
            "name": "Registration",
            "status": "FAIL",
            "detail": "skipped (no coordinator URL)",
        })
        rows.append({
            "name": "Heartbeat",
            "status": "FAIL",
            "detail": "skipped (no coordinator URL)",
        })
    else:
        base = url_check["url"].rstrip("/") + "/api/v1"
        health_status, _, health_error = get(f"{base}/health", 5.0)
        if health_status == 200:
            rows.append({
                "name": "Coordinator",
                "status": "OK",
                "detail": f"reachable at {url_check['url']} "
                f"({url_check.get('scope', '')})",
            })
        else:
            rows.append({
                "name": "Coordinator",
                "status": "FAIL",
                "detail": f"unreachable ({health_error or health_status}); "
                "start the coordinator first",
            })
        if node_id and health_status == 200:
            node_status, _, node_error = get(f"{base}/nodes/{node_id}", 5.0)
            if node_status == 200:
                rows.append({
                    "name": "Registration",
                    "status": "OK",
                    "detail": f"{node_id} visible in Nodes API",
                })
                rows.append({
                    "name": "Heartbeat",
                    "status": "OK",
                    "detail": "node record exists; the running loop "
                    "refreshes it every poll interval",
                })
            elif node_status == 404:
                rows.append({
                    "name": "Registration",
                    "status": "FAIL",
                    "detail": f"{node_id} not registered yet "
                    "(run install --bootstrap once)",
                })
                rows.append({
                    "name": "Heartbeat",
                    "status": "FAIL",
                    "detail": "no heartbeat without registration",
                })
            else:
                rows.append({
                    "name": "Registration",
                    "status": "FAIL",
                    "detail": f"lookup failed ({node_error or node_status})",
                })
                rows.append({
                    "name": "Heartbeat",
                    "status": "FAIL",
                    "detail": "unknown (registration lookup failed)",
                })
        else:
            rows.append({
                "name": "Registration",
                "status": "FAIL",
                "detail": "skipped (coordinator unreachable or no node id)",
            })
            rows.append({
                "name": "Heartbeat",
                "status": "FAIL",
                "detail": "skipped (coordinator unreachable or no node id)",
            })

    ollama = check_ollama(runner)
    rows.append({
        "name": "Ollama",
        "status": ollama["status"],
        "detail": ollama["detail"],
    })
    nvidia = check_nvidia(runner)
    rows.append({
        "name": "NVIDIA",
        "status": nvidia["status"],
        "detail": nvidia["detail"],
    })
    try:
        raw_caps = [
            part.strip()
            for part in str(config.get("MYCELIUM_NODE_CAPABILITIES", "") or "").split(",")
            if part.strip()
        ]
        caps = check_capabilities(raw_caps) if raw_caps else []
        rows.append({
            "name": "Capabilities",
            "status": "OK" if caps else "FAIL",
            "detail": ", ".join(caps) if caps else "none configured",
        })
    except (ValueError, TypeError) as error:
        rows.append({
            "name": "Capabilities",
            "status": "FAIL",
            "detail": str(error)[:120],
        })
    overall = all(
        row["status"] in ("OK", "AVAILABLE", "OPTIONAL") for row in rows
    )
    return {"ok": overall, "rows": rows, "config_path": path}


def uninstall_node(
    *,
    config_path: str | None = None,
    systemd_path: str | None = None,
    remove_config: bool = False,
    remove_venv: bool = False,
    repo_dir: str = "",
) -> dict:
    """Safe local uninstall. Server-side identity/audit is NEVER touched.

    Default removes only the user systemd unit. Config and venv removal
    are explicit opt-ins. Nothing here calls the coordinator.
    """
    path = config_path or default_config_path()
    unit = systemd_path or default_systemd_path()
    removed: list[str] = []
    kept: list[str] = []
    try:
        with open(unit, encoding="utf-8") as handle:
            unit_text = handle.read()
    except OSError:
        unit_text = ""
    if unit_text:
        if INSTALLER_MARKER in unit_text or "mycelium" in unit_text.lower():
            try:
                os.remove(unit)
                removed.append(unit)
            except OSError as error:
                return {"ok": False, "removed": removed, "kept": kept,
                        "error": f"cannot remove service file: {error}"}
        else:
            kept.append(f"{unit} (foreign file, kept)")
    if remove_config:
        try:
            os.remove(path)
            removed.append(path)
        except FileNotFoundError:
            pass
        except OSError as error:
            return {"ok": False, "removed": removed, "kept": kept,
                    "error": f"cannot remove config: {error}"}
    else:
        kept.append(f"{path} (identity kept)")
    if remove_venv and repo_dir:
        venv_dir = os.path.join(repo_dir, ".venv")
        if os.path.isdir(venv_dir):
            import shutil

            try:
                shutil.rmtree(venv_dir)
                removed.append(venv_dir)
            except OSError as error:
                return {"ok": False, "removed": removed, "kept": kept,
                        "error": f"cannot remove venv: {error}"}
    kept.append("server-side node identity/audit (always kept)")
    return {"ok": True, "removed": removed, "kept": kept, "error": ""}


