def validate_coordinator_url(url: str) -> dict:
    """Validate the coordinator URL. Loopback preferred; LAN allowed.

    Refused (fail-closed): empty, > 2000 chars, non-http(s) scheme,
    missing host, credentials embedded in the URL.
    """
    raw = str(url or "").strip()
    if not raw:
        return {"ok": False, "url": "", "scope": "", "error": "coordinator URL is required"}
    if len(raw) > 2000:
        return {"ok": False, "url": "", "scope": "", "error": "URL too long; refusing"}
    try:
        parsed = urlsplit(raw)
    except ValueError as error:
        return {"ok": False, "url": "", "scope": "", "error": f"URL unparsable: {error}"}
    if parsed.scheme.lower() not in ("http", "https"):
        return {
            "ok": False,
            "url": "",
            "scope": "",
            "error": "https/http URLs only; refusing",
        }
    host = (parsed.hostname or "").lower().rstrip(".")
    if not host:
        return {"ok": False, "url": "", "scope": "", "error": "URL has no host; refusing"}
    if parsed.username or parsed.password or "@" in parsed.netloc.split("]")[-1]:
        return {
            "ok": False,
            "url": "",
            "scope": "",
            "error": "credentials in URLs are refused",
        }
    if parsed.query or parsed.fragment:
        return {
            "ok": False,
            "url": "",
            "scope": "",
            "error": "base URL must not carry query or fragment",
        }
    if (
        host == "localhost"
        or host == "::1"
        or host == "127.0.0.1"
        or (host.startswith("127.") and host != "127.")
    ):
        scope = "loopback"
    else:
        scope = "lan"
    return {"ok": True, "url": raw.rstrip("/"), "scope": scope, "error": ""}


def validate_node_id(node_id: str) -> dict:
    """Mirror coordinator check_node_id: 1..80 chars of [a-zA-Z0-9._-]."""
    text = str(node_id or "").strip()
    if not text or len(text) > 80 or not NODE_ID_PATTERN.match(text):
        return {
            "ok": False,
            "error": "node_id must be 1..80 chars of [a-zA-Z0-9._-]",
        }
    return {"ok": True, "node_id": text, "error": ""}


def validate_poll_seconds(value: object) -> dict:
    """Poll interval must stay within 1..300 seconds."""
    try:
        seconds = float(str(value or "").strip() or DEFAULT_POLL_SECONDS)
    except (TypeError, ValueError):
        return {"ok": False, "error": "poll-seconds must be a number"}
    if not 1.0 <= seconds <= 300.0:
        return {"ok": False, "error": "poll-seconds must be 1..300"}
    return {"ok": True, "poll_seconds": seconds, "error": ""}


def check_capabilities(caps: list[str]) -> list[str]:
    """Fail-closed starter-set check. Coordinator contract wins."""
    try:
        from coordinator.app.linux_node import (
            check_capabilities as coordinator_check,
        )

        return coordinator_check(list(caps or []))
    except ImportError:
        pass
    if not isinstance(caps, list) or not caps:
        raise ValueError("capabilities must be a non-empty list")
    cleaned: list[str] = []
    for cap in caps:
        text = str(cap or "").strip()[:80]
        if not text:
            raise ValueError("empty capability")
        if text in ("*", "all", "shell", "shell.exec", "exec",
                    "command.run", "remote.shell") or "*" in text:
            raise ValueError(f"capability '{text}' is never granted")
        if text not in FALLBACK_LINUX_CAPABILITIES:
            raise ValueError(
                f"capability '{text}' is not in the Linux starter set"
            )
        if text not in cleaned:
            cleaned.append(text)
    return cleaned


def detect_capabilities(ollama_available: bool = False) -> list[str]:
    """Honest capability set: only what node_client can execute.

    Always: node.status, research.fetch, inventory.read (real executors
    in node_client/main.py). Ollama-backed research.search and
    analysis.ollama only when `ollama list` works. Never shell-like.
    """
    caps = list(ALWAYS_CAPABILITIES)
    if ollama_available:
        caps.extend(OLLAMA_CAPABILITIES)
    return check_capabilities(caps)


# ---------------------------------------------------------------------------
# local config (env file, chmod 600, identity preserving)
