"""Mycelium Linux node installer (P1 distribution layer).

This module DOES the install work; ``scripts/install_linux_node.sh``
is only a thin wrapper that prepares ``python3``/``venv`` and then
calls ``python -m node_client.install install``.

Everything here is stdlib-only (plus optional, guarded imports) so it
runs on a bare laptop with Python >= 3.11. No new queue, no new auth,
no new scheduler: identity, tokens, capabilities, registration,
heartbeat and task claiming all follow the existing coordinator
contract (``coordinator/app/nodes.py``, ``coordinator/app/linux_node.py``,
``coordinator/app/main.py``) and the existing pull-only
``node_client/main.py`` loop.

Subcommands::

    python -m node_client.install install [--coordinator URL ...]
    python -m node_client.install doctor [--config PATH]
    python -m node_client.install print-systemd [...]
    python -m node_client.install uninstall [...]

Secrets (``MYCELIUM_NODE_TOKEN``) live only in the local env file
(``~/.config/mycelium/node.env``, chmod 600) or the process
environment. They are never printed, never logged, never committed.
"""

