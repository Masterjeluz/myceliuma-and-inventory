def parse_os_release(text: str) -> dict[str, str]:
    """Parse /etc/os-release content into a small dict."""
    info: dict[str, str] = {}
    for line in str(text or "").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        info[key.strip()] = value.strip().strip('"').strip("'")[:120]
    return info


def detect_os(
    system: str | None = None,
    release_text: str | None = None,
) -> dict[str, str]:
    """Detect OS name/arch/distro. Never raises; missing data is ''."""
    detected_system = system if system is not None else platform.system()
    machine = platform.machine() or ""
    distro = ""
    if release_text is None:
        try:
            with open("/etc/os-release", encoding="utf-8") as handle:
                release_text = handle.read()
        except OSError:
            release_text = ""
    try:
        parsed = parse_os_release(release_text or "")
        distro = parsed.get("PRETTY_NAME", "") or " ".join(
            part
            for part in (parsed.get("NAME", ""), parsed.get("VERSION_ID", ""))
            if part
        )
    except Exception:
        distro = ""
    return {
        "system": detected_system,
        "machine": machine,
        "distro": distro[:120],
        "is_linux": detected_system == "Linux",
    }


def check_python_version(version: tuple[int, ...] | None = None) -> dict:
    """Python >= 3.11 is required (matches pyproject requires-python)."""
    current = version if version is not None else sys.version_info[:3]
    ok = len(current) >= 2 and (current[0], current[1]) >= (3, 11)
    return {
        "name": "Python",
        "status": "OK" if ok else "FAIL",
        "detail": (
            f"{current[0]}.{current[1]}.{current[2] if len(current) > 2 else 0} "
            f"({ 'meets' if ok else 'needs' } >= 3.11)"
        ),
    }


def default_runner(
    cmd: list[str], timeout: float = 5.0
) -> tuple[int, str]:
    """Run a command, return (returncode, stdout). Never raises."""
    try:
        proc = subprocess.run(
            cmd, capture_output=True, text=True, timeout=timeout
        )
        return proc.returncode, (proc.stdout or "").strip()[:2000]
    except Exception:
        return 127, ""


Runner = Callable[[list[str], float], tuple[int, str]]


def check_git(runner: Runner = default_runner) -> dict:
    """Git is required to clone/update the repo; fatal when missing."""
    code, out = runner(["git", "--version"], 5.0)
    if code == 0 and out:
        return {"name": "Git", "status": "OK", "detail": out.splitlines()[0][:80]}
    return {
        "name": "Git",
        "status": "FAIL",
        "detail": "git not found (install with: sudo apt install -y git)",
    }


def check_ollama(runner: Runner = default_runner) -> dict:
    """Ollama is OPTIONAL: the node registers without it."""
    code, out = runner(["ollama", "list"], 5.0)
    if code != 0:
        return {
            "name": "Ollama",
            "status": "OPTIONAL",
            "detail": "not found (node still registers; "
            "ollama-backed capabilities stay off)",
        }
    models = [
        line.split()[0]
        for line in out.splitlines()[1:]
        if line.strip() and line.split()
    ][:20]
    detail = f"available ({len(models)} models)" if models else "available"
    return {"name": "Ollama", "status": "AVAILABLE", "detail": detail}


def check_nvidia(runner: Runner = default_runner) -> dict:
    """NVIDIA GPU is OPTIONAL: detected via nvidia-smi when present."""
    code, out = runner(["nvidia-smi", "-L"], 5.0)
    if code != 0 or not out:
        return {
            "name": "NVIDIA",
            "status": "OPTIONAL",
            "detail": "not detected (CPU-only node)",
        }
    first = out.splitlines()[0][:100]
    return {"name": "NVIDIA", "status": "AVAILABLE", "detail": first}


def memory_mb(
    meminfo_text: str | None = None, use_psutil: bool = True
) -> int:
    """Total RAM in MiB. psutil first, /proc/meminfo fallback, else 0."""
    if use_psutil:
        try:
            import psutil

            return int(psutil.virtual_memory().total // (1024 * 1024))
        except Exception:
            pass
    text = meminfo_text
    if text is None:
        try:
            with open("/proc/meminfo", encoding="utf-8") as handle:
                text = handle.read(4096)
        except OSError:
            return 0
    try:
        for line in str(text or "").splitlines():
            if line.startswith("MemTotal:"):
                kb = int(line.split()[1])
                return kb // 1024
    except (IndexError, ValueError):
        return 0
    return 0


def cpu_count() -> int:
    """Logical CPU count, at least 1."""
    try:
        return os.cpu_count() or 1
    except Exception:
        return 1


def system_info(runner: Runner = default_runner) -> dict:
    """One snapshot for the installer summary. Optional parts never fail."""
    info = detect_os()
    info["python"] = check_python_version()
    info["git"] = check_git(runner)
    info["ollama"] = check_ollama(runner)
    info["nvidia"] = check_nvidia(runner)
    info["memory_mb"] = memory_mb()
    info["cpu_count"] = cpu_count()
    return info


